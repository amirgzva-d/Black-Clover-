export function normalizePersianCommand(input=''){
  let text=String(input).normalize('NFKC').replace(/[۰-۹٠-٩]/g,d=>DIGITS[d]??d).replace(/ي/g,'ی').replace(/ك/g,'ک').replace(/[ـ]/g,'').replace(/\s+/g,' ').trim();
  for(const [pattern,replacement] of RULES)text=text.replace(pattern,replacement);
  return text.trim();
}

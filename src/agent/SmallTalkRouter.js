const norm=s=>String(s??'').normalize('NFKC').replace(/ي/g,'ی').replace(/ك/g,'ک').replace(/[!?؟،,.]+/g,' ').replace(/\s+/g,' ').trim().toLowerCase();
const only=(s,re)=>s.length<=120&&re.test(s);
export function matchSmallTalk(input=''){
  const s=norm(input);if(!s)return null;
  if(only(s,/^(?:سلام|درود|هی|hello|hi)(?: ماریا)?$/i))return 'سلام ✦ من اینجام. چی کار کنیم؟';
  if(only(s,/(?:حالت چطوره|خوبی|حالت خوبه|چطوری)(?: ماریا)?$/i))return 'خوبم، آماده و سرحال ✦ تو بگو الان چی لازم داری.';
  if(only(s,/^(?:چه خبر|چه خبرا)(?: ماریا)?$/i))return 'همه‌چیز آماده‌ست؛ من منتظرم ببینم این بار چه مأموریتی داری.';
  if(only(s,/^(?:مرسی|ممنون|دمت گرم|تشکر|thanks|thank you).*$/i))return 'خواهش می‌کنم ✦ هر وقت خواستی ادامه می‌دیم.';
  if(only(s,/^(?:خداحافظ|فعلا|بای|bye).*$/i))return 'فعلاً ✦ هر وقت صدام کنی دوباره اینجام.';
  if(only(s,/^(?:صبح بخیر).*$/i))return 'صبح بخیر ✦ امیدوارم امروز رو خوب و سریع جلو ببریم.';
  if(only(s,/^(?:شب بخیر).*$/i))return 'شب بخیر ✦ من اینجام؛ تو استراحت کن.';
  if(only(s,/(?:تو کی هستی|کی هستی|اسمت چیه|اسم تو چیه)/i))return 'من ماریا هستم؛ دستیار دسکتاپ Black Clover. هم می‌تونم باهات حرف بزنم، هم روی سیستم کار انجام بدم.';
  if(only(s,/(?:دوستم داری|منو دوست داری)/i))return 'خب، از هم‌صحبتی باهات خوشم میاد ✦ ولی بیا ببینیم چه کاری داری که انجام بدیم.';
  return null;
}

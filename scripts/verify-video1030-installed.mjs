import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const asar=require('@electron/asar');
const archive=path.join(os.homedir(),'AppData','Local','Programs','Black Clover Maria','resources','app.asar');
assert.ok(fs.existsSync(archive),'Installed ASAR missing');
const pkg=JSON.parse(asar.extractFile(archive,'package.json').toString('utf8'));
assert.equal(pkg.version,'0.8.0-beta.3');
const names=asar.listPackage(archive);
const top=names.find(p=>/dist\/assets\/topIslandV4-[^/]+\.js$/.test(p.replace(/\\/g,'/')));
const style=names.find(p=>/dist\/assets\/topIslandV4-[^/]+\.css$/.test(p.replace(/\\/g,'/')));
assert.ok(top&&style,'Renderer bundles missing from installed package');
const js=asar.extractFile(archive,top.replace(/^[/\\\\]+/,'')).toString('utf8');
const css=asar.extractFile(archive,style.replace(/^[/\\\\]+/,'')).toString('utf8');
assert.ok(js.includes('maria-film-particle')||js.includes('FILM_1030_DURATION')||js.includes('data-film1030-play'),'Installed UI missing film1030 runtime');
assert.ok(css.includes('maria-film-heart')&&css.includes('maria-film-ring'),'Installed CSS missing film1030 identity');
console.log(JSON.stringify({ok:true,installed:archive,version:pkg.version,topIslandBundle:top,topIslandCSS:style,film1030:true},null,2));
